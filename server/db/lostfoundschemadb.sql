CREATE TABLE IF NOT EXISTS public.users (
  user_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL UNIQUE,
  password_hash text,
  role text NOT NULL DEFAULT 'student',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT users_kent_email_chk CHECK (lower(email) LIKE '%@kent.edu'),
  CONSTRAINT users_role_chk CHECK (role IN ('student', 'faculty', 'admin'))
);

CREATE TABLE IF NOT EXISTS public.items (
  item_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category text,
  primary_color text,
  material text,
  description_raw varchar(3000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.reports (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  user_id uuid REFERENCES public.users (user_id) ON DELETE SET NULL,
  item_id uuid REFERENCES public.items (item_id) ON DELETE SET NULL,
  status text NOT NULL,
  location text,
  area text,
  estimated_date date,
  estimated_start time,
  estimated_end time,
  category text,
  color text,
  material text,
  description_raw varchar(3000),
  image_path text,
  image_hash text,
  mobileclip_embedding jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

