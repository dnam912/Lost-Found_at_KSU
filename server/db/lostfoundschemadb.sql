CREATE INDEX IF NOT EXISTS reports_item_id_idx ON public.reports (item_id);
CREATE INDEX IF NOT EXISTS reports_status_idx ON public.reports (status);
CREATE INDEX IF NOT EXISTS reports_estimated_date_idx ON public.reports (estimated_date);
CREATE INDEX IF NOT EXISTS reports_created_at_idx ON public.reports (created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS reports_image_hash_uidx
  ON public.reports (image_hash)
  WHERE image_hash IS NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'reports_user_id_fkey'
  ) THEN
    ALTER TABLE public.reports
      ADD CONSTRAINT reports_user_id_fkey
      FOREIGN KEY (user_id) REFERENCES public.users (user_id) ON DELETE SET NULL;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'reports_item_id_fkey'
  ) THEN
    ALTER TABLE public.reports
      ADD CONSTRAINT reports_item_id_fkey
      FOREIGN KEY (item_id) REFERENCES public.items (item_id) ON DELETE SET NULL;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'reports_estimated_time_window_chk'
  ) THEN
    ALTER TABLE public.reports
      ADD CONSTRAINT reports_estimated_time_window_chk CHECK (
        estimated_start IS NULL
        OR estimated_end IS NULL
        OR estimated_start <= estimated_end
      );
  END IF;
END;
$$;

