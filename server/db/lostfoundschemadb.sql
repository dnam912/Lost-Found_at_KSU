CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DO $$
BEGIN
  IF to_regclass('public.reports') IS NOT NULL THEN
    DROP TRIGGER IF EXISTS reports_set_updated_at ON public.reports;
    CREATE TRIGGER reports_set_updated_at
      BEFORE UPDATE ON public.reports
      FOR EACH ROW
      EXECUTE PROCEDURE public.set_updated_at();
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.enforce_kent_email()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.email IS NULL OR lower(NEW.email) NOT LIKE '%@kent.edu' THEN
    RAISE EXCEPTION 'Only @kent.edu accounts are allowed';
  END IF;
  RETURN NEW;
END;
$$;

DO $$
BEGIN
  IF to_regclass('public.users') IS NOT NULL THEN
    DROP TRIGGER IF EXISTS enforce_kent_email_on_users ON public.users;
    CREATE TRIGGER enforce_kent_email_on_users
      BEFORE INSERT OR UPDATE OF email ON public.users
      FOR EACH ROW
      EXECUTE PROCEDURE public.enforce_kent_email();
  END IF;
END;
$$;

