
BEGIN;

-- REVISED: Shared authentication sessions for Web and iOS
-- User accounts are managed in the existing users table
-- Both Web and iOS reports reference reports.user_id
-- The users.role column is retained (default: 'student')


CREATE TABLE IF NOT EXISTS app_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT app_sessions_expiry_check CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS app_sessions_user_id_idx
    ON app_sessions(user_id);

CREATE INDEX IF NOT EXISTS app_sessions_expiry_idx
    ON app_sessions(expires_at);

COMMIT;
