BEGIN;

ALTER TABLE app_users
    ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS app_email_verification_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    CONSTRAINT app_email_verification_expiry_check CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS app_email_verification_user_idx
    ON app_email_verification_tokens(user_id);
CREATE INDEX IF NOT EXISTS app_email_verification_expiry_idx
    ON app_email_verification_tokens(expires_at);

COMMIT;